// Scripts that re-run a ResearchHub regression in R, MATLAB, SPSS or Stata on
// the exported data.csv, so a supervisor can check every number.
import { columns, mArr, mq, rq, rVec, sq, type Column, type ScriptLang } from './exportPack';
import type { Fit, ModelSpec } from './regression';
import { findVar, type Dataset, type StudioVar } from './studio';

const today = () => new Date().toISOString().slice(0, 10);

export function modelScript(lang: ScriptLang, spec: ModelSpec, ds: Dataset, fit: Fit): string {
  const cols = columns(ds);
  const y = findVar(ds, spec.outcome)!;
  const xs = spec.predictors.map((p) => findVar(ds, p)).filter((v): v is StudioVar => !!v);
  const logistic = fit.kind === 'logistic';
  const event = fit.kind === 'logistic' ? fit.event : '';
  const weighted = fit.weighted;
  const terms = (dummy: (v: StudioVar) => string[], cat: (v: StudioVar) => string) =>
    xs.flatMap((v) => (v.kind === 'multi' ? dummy(v) : v.kind === 'categorical' ? [cat(v)] : [v.name]));
  const dummies = (v: StudioVar) => v.categories.map((_, j) => `${v.name}_${j + 1}`);
  const title = `${logistic ? 'Logistic' : 'Linear'} regression of ${y.name} (${y.label})`;
  const strs = cols.filter((c: Column) => c.kind === 'string').map((c) => c.name);

  if (lang === 'r') {
    const L = [`# ${title}`, `# Generated by ResearchHub (ScreenLab) on ${today()} from ${ds.n} responses. Base R only.`, '',
      `d <- read.csv("data.csv", na.strings = "", fileEncoding = "UTF-8", colClasses = c(${strs.map((s) => `${s} = "character"`).join(', ')}))`];
    for (const v of xs) {
      if (v.kind === 'categorical') L.push(`d$${v.name} <- factor(d$${v.name}, levels = ${rVec(v.categories)})   # first level is the reference`);
      if (v.kind === 'multi') L.push(...dummies(v).map((n) => `d$${n}[is.na(d$${n})] <- 0   # not ticked`));
    }
    if (logistic) L.push(`d$event <- as.integer(${y.kind === 'multi' ? `d$${dummies(y)[y.categories.indexOf(event)]} == 1` : `d$${y.name} == ${y.kind === 'numeric' ? event : rq(event)}`})   # 1 = ${event}`);
    const f = `${logistic ? 'event' : y.name} ~ ${terms(dummies, (v) => v.name).join(' + ')}`;
    if (logistic) L.push(`m <- glm(${f}, data = d, family = binomial${weighted ? ', weights = weight' : ''})`, 'summary(m)', 'exp(cbind(OR = coef(m), confint.default(m)))   # odds ratios with 95% CI');
    else L.push(`m <- lm(${f}, data = d${weighted ? ', weights = weight' : ''})`, 'summary(m)', 'confint(m)');
    if (weighted) L.push('', '# For design-based standard errors: library(survey); des <- svydesign(ids = ~1, weights = ~weight, data = d)', `# summary(svy${logistic ? 'glm' : 'glm'}(${f}, design = des${logistic ? ', family = quasibinomial' : ''}))`);
    return L.join('\n') + '\n';
  }

  if (lang === 'matlab') {
    const L = [`% ${title}`, `% Generated by ResearchHub (ScreenLab) on ${today()} from ${ds.n} responses.`, '% Needs the Statistics and Machine Learning Toolbox (fitlm / fitglm).', '',
      'opts = detectImportOptions("data.csv", "Encoding", "UTF-8");',
      ...(strs.length ? [`opts = setvartype(opts, ${mArr(strs)}, "string");`] : []),
      `opts = setvartype(opts, ${mArr(['Response', ...cols.filter((c) => c.kind !== 'string').map((c) => c.name)])}, "double");`,
      'T = readtable("data.csv", opts);'];
    for (const v of xs) {
      if (v.kind === 'categorical') L.push(`T.${v.name} = categorical(T.${v.name}, ${mArr(v.categories)});   % first answer is the reference`);
      if (v.kind === 'multi') L.push(...dummies(v).map((n) => `T.${n}(isnan(T.${n})) = 0;   % not ticked`));
    }
    if (logistic) L.push(`T.event = double(${y.kind === 'multi' ? `T.${dummies(y)[y.categories.indexOf(event)]} == 1` : `T.${y.name} == ${y.kind === 'numeric' ? event : mq(event)}`});   % 1 = ${event}`);
    const f = `${logistic ? 'event' : y.name} ~ ${terms(dummies, (v) => v.name).join(' + ')}`;
    const w = weighted ? ', "Weights", T.weight' : '';
    L.push(logistic ? `m = fitglm(T, ${mq(f)}, "Distribution", "binomial"${w})` : `m = fitlm(T, ${mq(f)}${w})`);
    if (logistic) L.push('oddsRatios = exp(m.Coefficients.Estimate)', 'ci = exp(coefCI(m))');
    return L.join('\n') + '\n';
  }

  if (lang === 'spss') {
    const fmt = (c: Column) => (c.kind === 'dummy' ? 'F1.0' : c.kind === 'number' ? 'F12.6' : c.v.kind === 'date' ? 'A10' : 'A255');
    const L = [`* ${title}.`, `* Generated by ResearchHub (ScreenLab) from ${ds.n} responses. Check the FILE path, then Run All.`, '',
      "GET DATA /TYPE=TXT /FILE='data.csv' /ENCODING='UTF8' /DELCASE=LINE /DELIMITERS=\",\" /QUALIFIER='\"'",
      '  /ARRANGEMENT=DELIMITED /FIRSTCASE=2 /VARIABLES=Response F8.0', ...cols.map((c, i) => `  ${c.name} ${fmt(c)}${i === cols.length - 1 ? '.' : ''}`), 'EXECUTE.'];
    for (const v of xs) if (v.kind === 'multi') L.push(...dummies(v).map((n) => `RECODE ${n} (SYSMIS=0).`));
    const cats = xs.filter((v) => v.kind === 'categorical');
    for (const v of cats) L.push(`RECODE ${v.name} ${v.categories.map((c, i) => `(${sq(c)}=${i + 1})`).join(' ')} INTO ${v.name}_n.`, `VALUE LABELS ${v.name}_n ${v.categories.map((c, i) => `${i + 1} ${sq(c)}`).join(' ')}.`);
    if (logistic) L.push(`COMPUTE event = ${y.kind === 'multi' ? `${dummies(y)[y.categories.indexOf(event)]} = 1` : `${y.name} = ${y.kind === 'numeric' ? event : sq(event)}`}.`);
    L.push('EXECUTE.', ...(weighted ? ['WEIGHT BY weight.'] : []));
    const preds = terms(dummies, (v) => `${v.name}_n`);
    if (logistic) {
      L.push(`LOGISTIC REGRESSION VARIABLES event /METHOD=ENTER ${preds.join(' ')}`, ...cats.map((v) => `  /CATEGORICAL=${v.name}_n /CONTRAST (${v.name}_n)=Indicator(1)`), '  /PRINT=CI(95).');
    } else {
      // 0/1 dummies against the first answer, so the estimates match ResearchHub and R.
      const dum: string[] = [];
      for (const v of cats) v.categories.slice(1).forEach((_, j) => { const n = `${v.name}_d${j + 2}`; dum.push(n); L.push(`COMPUTE ${n} = (${v.name}_n = ${j + 2}).`); });
      L.push('EXECUTE.', `REGRESSION /STATISTICS COEFF CI(95) R ANOVA /DEPENDENT ${y.name} /METHOD=ENTER ${[...preds.filter((p) => !p.endsWith('_n')), ...dum].join(' ')}.`);
    }
    if (weighted) L.push('WEIGHT OFF.');
    return L.join('\n') + '\n';
  }

  // Stata
  const tq = (s: string) => `"${s.replace(/"/g, "'").replace(/\r?\n/g, ' ').slice(0, 80)}"`;
  const strIdx = cols.map((c, i) => (c.kind === 'string' ? i + 2 : 0)).filter(Boolean);
  const L = [`* ${title}`, `* Generated by ResearchHub (ScreenLab) from ${ds.n} responses. cd to the folder with data.csv, then run.`, '',
    `import delimited using "data.csv", varnames(1) case(preserve) encoding("utf-8")${strIdx.length ? ` stringcols(${strIdx.join(' ')})` : ''} clear`];
  for (const v of xs) {
    if (v.kind === 'categorical') L.push(`label define ${v.name}_l ${v.categories.map((c, i) => `${i + 1} ${tq(c)}`).join(' ')}`, `generate ${v.name}_c = .`,
      ...v.categories.map((c, i) => `replace ${v.name}_c = ${i + 1} if ${v.name} == ${tq(c)}`), `label values ${v.name}_c ${v.name}_l`);
    if (v.kind === 'multi') L.push(...dummies(v).map((n) => `replace ${n} = 0 if missing(${n})`));
  }
  if (logistic) L.push(`generate event = ${y.kind === 'multi' ? `${dummies(y)[y.categories.indexOf(event)]} == 1` : `${y.name} == ${y.kind === 'numeric' ? event : tq(event)}`} if !missing(${y.kind === 'multi' ? dummies(y)[0] : y.name})`);
  const preds = terms(dummies, (v) => `i.${v.name}_c`).join(' ');
  const w = weighted ? ' [pweight = weight]' : '';
  L.push(logistic ? `logit event ${preds}${w}, or` : `regress ${y.name} ${preds}${w}`);
  if (weighted) L.push('* pweight gives robust standard errors; R and ResearchHub show model-based ones, so SEs differ slightly.');
  return L.join('\n') + '\n';
}
