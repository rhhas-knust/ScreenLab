const rq = (s: string) => `"${s.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\r?\n/g, ' ')}"`;
const rVec = (xs: string[]) => `c(${xs.map(rq).join(', ')})`;
function rCat(v: StudioVar, name: string): string[] {
  if (v.kind === 'multi') return [`${name}_cats <- ${rVec(v.categories)}`, `${name}_X <- d[, ${rVec(v.categories.map((_, j) => `${v.name}_${j + 1}`))}] == 1`];
  return [`${name} <- factor(d$${v.name}, levels = ${v.scale ? `c(${v.categories.join(', ')})` : rVec(v.categories)})`];
}

function rScript(spec: ChartSpec, ds: Dataset, chart: ChartResult, cols: Column[]): string {
  const x = findVar(ds, spec.x)!, y = findVar(ds, spec.y), g = findVar(ds, spec.group);
  const strs = cols.filter((c) => c.kind === 'string').map((c) => c.name);
  const lab = `main = ${rq(chart.title)}, xlab = ${rq(chart.xlabel)}, ylab = ${rq(chart.ylabel)}`;
  const L = [
    `# ${chart.title}`, `# Generated by ResearchHub (ScreenLab) on ${new Date().toISOString().slice(0, 10)} from ${ds.n} responses.`,
    '# Base R only. setwd() to the folder with data.csv, then source this file.', '',
    `d <- read.csv("data.csv", na.strings = "", fileEncoding = "UTF-8", colClasses = c(${strs.map((s) => `${s} = "character"`).join(', ')}))`, '',
  ];
  switch (spec.type) {
    case 'bar': case 'barh': case 'pie': {
      L.push(...rCat(x, 'x'));
      const hz = spec.type === 'barh' ? ', horiz = TRUE, las = 1' : '';
      if (spec.type === 'pie') { L.push(x.kind === 'multi' ? 'counts <- colSums(x_X, na.rm = TRUE)' : 'counts <- table(x)', `pie(counts[counts > 0], main = ${rq(chart.title)})`); break; }
      if (!g || g.name === x.name) {
        L.push(x.kind === 'multi' ? 'counts <- colSums(x_X, na.rm = TRUE); names(counts) <- x_cats; n <- sum(rowSums(!is.na(x_X)) > 0)' : 'counts <- table(x); n <- sum(counts)');
        if (spec.sort) L.push('counts <- sort(counts, decreasing = TRUE)');
        L.push(`barplot(${spec.percent ? '100 * counts / n' : 'counts'}, ${lab}${hz})`);
      } else if (x.kind !== 'multi' && g.kind !== 'multi') {
        L.push(...rCat(g, 'g'), 'tab <- table(x, g)', 'print(tab)',
          `barplot(${spec.percent ? 't(100 * prop.table(tab, 2))' : 't(tab)'}, beside = ${spec.stacked ? 'FALSE' : 'TRUE'}, legend.text = TRUE, ${lab}${hz})`,
          'chisq.test(tab)   # chi-square test of independence');
      } else {
        L.push('# One of these is a checkbox question: count each ticked option per group.', ...rCat(g, 'g'),
          ...(x.kind === 'multi' ? [g.kind === 'multi' ? 'tab <- t(x_X) %*% g_X' : 'tab <- sapply(levels(g), function(k) colSums(x_X[g %in% k, , drop = FALSE], na.rm = TRUE))']
            : ['tab <- sapply(seq_along(g_cats), function(j) table(x[g_X[, j] %in% TRUE]))']),
          `barplot(t(tab), beside = ${spec.stacked ? 'FALSE' : 'TRUE'}, legend.text = TRUE, ${lab}${hz})`);
      }
      break;
    }
    case 'histogram':
      L.push(`hist(d$${x.name}, breaks = ${x.scale ? `seq(${Number(x.categories[0]) - 0.5}, ${Number(x.categories.at(-1)) + 0.5}, 1)` : chart.model.kind === 'hist' ? chart.model.bins.length : 10}, ${lab})`, `summary(d$${x.name}); sd(d$${x.name}, na.rm = TRUE)`);
      break;
    case 'box': case 'means': {
      const val = y ?? x, by = y ? (isCat(x) ? x : g) : g;
      if (!by) { L.push(`boxplot(d$${val.name}, ${lab})`); break; }
      if (by.kind === 'multi') { L.push(`# ${by.name} is a checkbox question, so respondents can be in several groups; no test is run.`, ...rCat(by, 'g'),
        `boxplot(lapply(seq_along(g_cats), function(j) d$${val.name}[g_X[, j] %in% TRUE]), names = g_cats, ${lab})`); break; }
      L.push(...rCat(by, 'g'));
      if (spec.type === 'box') L.push(`boxplot(d$${val.name} ~ g, ${lab})`);
      else L.push(`m <- tapply(d$${val.name}, g, mean, na.rm = TRUE)`, `s <- tapply(d$${val.name}, g, sd, na.rm = TRUE)`, `n <- tapply(!is.na(d$${val.name}), g, sum)`,
        'half <- qt(0.975, n - 1) * s / sqrt(n)', `bp <- barplot(m, ylim = c(0, max(m + half, na.rm = TRUE) * 1.1), ${lab})`, 'arrows(bp, m - half, bp, m + half, angle = 90, code = 3, length = 0.05)');
      L.push(`if (nlevels(droplevels(g[!is.na(d$${val.name})])) == 2) print(t.test(d$${val.name} ~ g)) else print(summary(aov(d$${val.name} ~ g)))`);
      break;
    }
    case 'scatter':
      L.push(`plot(d$${x.name}, d$${y?.name}, pch = 19, ${lab})`, ...(spec.fit !== false ? [`abline(lm(${y?.name} ~ ${x.name}, data = d), lwd = 2)`] : []), `cor.test(d$${x.name}, d$${y?.name})`, `summary(lm(${y?.name} ~ ${x.name}, data = d))`);
      break;
    case 'line':
      L.push(`tab <- table(as.Date(d$${x.name}))`, `y <- ${spec.cumulative ? 'cumsum(as.numeric(tab))' : 'as.numeric(tab)'}`, `plot(as.Date(names(tab)), y, type = "b", pch = 19, ${lab})`);
      break;
    case 'heatmap': {
      const col = (y ?? g)!;
      if (x.kind === 'multi' || col.kind === 'multi') { L.push('# Heatmaps of checkbox questions: see the counts table in ResearchHub.'); break; }
      L.push(...rCat(x, 'x'), ...rCat(col, 'g'), 'tab <- table(x, g)', 'print(tab)', `heatmap(unclass(tab), Rowv = NA, Colv = NA, scale = "none", main = ${rq(chart.title)})`, 'chisq.test(tab)');
      break;
    }
  }
  L.push('', '# Results shown in ResearchHub, for checking:', ...chart.stats.map((s) => `#   ${s}`));
  return L.join('\n') + '\n';
}

