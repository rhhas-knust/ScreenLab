const mq = (s: string) => `"${s.replace(/"/g, '""').replace(/\r?\n/g, ' ')}"`;
const mArr = (xs: string[]) => `[${xs.map(mq).join(', ')}]`;

/** MATLAB lines that define `name` as a categorical (or `nameX` as a 0/1 matrix for checkboxes). */
function mCat(v: StudioVar, name: string): string[] {
  if (v.kind === 'multi') {
    return [`${name}Cats = ${mArr(v.categories)};`, `${name}X = T{:, ${mArr(v.categories.map((_, j) => `${v.name}_${j + 1}`))}} == 1;   % one column per option`,
      `${name}Answered = any(~isnan(T{:, ${mArr(v.categories.map((_, j) => `${v.name}_${j + 1}`))}}), 2);`];
  }
  if (v.scale) return [`${name}Cats = ${mArr(v.categories)};`, `${name} = categorical(T.${v.name}, [${v.categories.join(' ')}], ${name}Cats);`, `${name}Answered = ~isundefined(${name});`];
  return [`${name}Cats = ${mArr(v.categories)};`, `${name} = categorical(T.${v.name}, ${name}Cats);`, `${name}Answered = ~isundefined(${name});`];
}
const mCounts = (v: StudioVar, name: string, rows = '') =>
  v.kind === 'multi' ? `sum(${name}X(${rows || ':'}, :), 1)'` : `countcats(${name}${rows ? `(${rows})` : ''})`;
const mIn = (v: StudioVar, name: string, j: string) => (v.kind === 'multi' ? `${name}X(:, ${j})` : `${name} == ${name}Cats(${j})`);

function matlab(spec: ChartSpec, ds: Dataset, chart: ChartResult, cols: Column[]): string {
  const x = findVar(ds, spec.x)!, y = findVar(ds, spec.y), g = findVar(ds, spec.group);
  const strs = cols.filter((c) => c.kind === 'string').map((c) => c.name);
  const L: string[] = [
    `% ${chart.title}`,
    `% Generated by ResearchHub (ScreenLab) on ${new Date().toISOString().slice(0, 10)} from ${ds.n} responses.`,
    '% Put this file in the same folder as data.csv and press Run. Needs base MATLAB R2020a or newer.',
    '% codebook.csv lists every variable (Q1, Q2 …) with its full question text.',
    '',
    'opts = detectImportOptions("data.csv", "Encoding", "UTF-8");',
    ...(strs.length ? [`opts = setvartype(opts, ${mArr(strs)}, "string");`] : []),
    `opts = setvartype(opts, ${mArr(['Response', ...cols.filter((c) => c.kind !== 'string').map((c) => c.name)])}, "double");`,
    'T = readtable("data.csv", opts);',
    '',
  ];
  const labels = () => [`title(${mq(chart.title)});`, ...(chart.xlabel ? [`xlabel(${mq(chart.xlabel)});`] : []), ...(chart.ylabel ? [`ylabel(${mq(chart.ylabel)});`] : [])];
  switch (spec.type) {
    case 'bar': case 'barh': {
      const fn = spec.type;
      L.push(...mCat(x, 'x'));
      if (!g || g.name === x.name) {
        L.push(`counts = ${mCounts(x, 'x')};`, 'n = sum(xAnswered);');
        L.push(spec.percent ? 'values = 100 * counts / n;' : 'values = counts;');
        if (spec.sort) L.push('[values, order] = sort(values, "descend");', 'xCats = xCats(order);');
        L.push('figure;', `${fn}(categorical(xCats, xCats), values);`);
      } else {
        L.push(...mCat(g, 'g'), 'counts = zeros(numel(xCats), numel(gCats));', 'totals = zeros(1, numel(gCats));', 'for j = 1:numel(gCats)',
          `    in = ${mIn(g, 'g', 'j')} & xAnswered;`, `    counts(:, j) = ${mCounts(x, 'x', 'in')};`, '    totals(j) = sum(in);', 'end');
        L.push(spec.percent ? 'values = 100 * counts ./ totals;' : 'values = counts;');
        L.push('figure;', `${fn}(categorical(xCats, xCats), values${spec.stacked ? ', "stacked"' : ''});`, 'legend(gCats, "Location", "best");');
        if (x.kind !== 'multi' && g.kind !== 'multi') L.push('', '% Chi-square test (Statistics and Machine Learning Toolbox):', '% [tbl, chi2, p] = crosstab(x, g)');
      }
      L.push(...labels());
      break;
    }
    case 'pie':
      L.push(...mCat(x, 'x'), `counts = ${mCounts(x, 'x')};`, 'keep = counts > 0;   % pie leaves out empty slices', 'figure;', 'pie(counts(keep), cellstr(xCats(keep)));', `title(${mq(chart.title)});`);
      break;
    case 'histogram':
      L.push('figure;', x.scale ? `histogram(T.${x.name}, "BinMethod", "integers");` : `histogram(T.${x.name}, ${chart.model.kind === 'hist' ? chart.model.bins.length : 10});`, ...labels(),
        '', `fprintf("mean %.2f, SD %.2f, median %.2f\\n", mean(T.${x.name}, "omitnan"), std(T.${x.name}, "omitnan"), median(T.${x.name}, "omitnan"));`);
      break;
    case 'box': case 'means': {
      const val = y ?? x, by = y ? (isCat(x) ? x : g) : g;
      if (spec.type === 'box' && (!by || by.kind === 'multi')) {
        if (by) L.push(`% ${by.name} is a checkbox question (people can be in several groups), so this shows all answers together.`);
        L.push('figure;', `boxchart(T.${val.name});`, ...labels());
        break;
      }
      L.push(...mCat(by!, 'g'));
      if (spec.type === 'box') {
        L.push('figure;', `boxchart(g, T.${val.name});`, ...labels());
      } else {
        const crit = by!.categories.map((c) => {
          const xs = numsOf(val).filter((v, i): v is number => v != null && by!.values[i] != null && (Array.isArray(by!.values[i]) ? (by!.values[i] as string[]).includes(c) : String(by!.values[i]) === c));
          return xs.length > 1 ? round(tCrit95(xs.length - 1), 4) : 0;
        });
        L.push(`y = T.${val.name};`, 'k = numel(gCats);', 'm = nan(1, k); ci = nan(1, k);',
          `tcrit = [${crit.join(' ')}];   % t(0.975, n - 1) for each group, as tinv would give`,
          'for j = 1:k', `    v = y(${mIn(by!, 'g', 'j')} & ~isnan(y));`, '    m(j) = mean(v);', '    ci(j) = tcrit(j) * std(v) / sqrt(numel(v));', 'end',
          'figure;', 'bar(1:k, m); hold on;', 'errorbar(1:k, m, ci, "k", "LineStyle", "none", "LineWidth", 1.5); hold off;', 'xticks(1:k); xticklabels(gCats);', ...labels());
      }
      if (by!.kind !== 'multi') L.push('', '% Tests (Statistics and Machine Learning Toolbox):', `% p = anova1(T.${val.name}, g)`, `% [h, p] = ttest2(T.${val.name}(g == gCats(1)), T.${val.name}(g == gCats(2)), "Vartype", "unequal")`);
      break;
    }
    case 'scatter':
      L.push(`x = T.${x.name}; y = T.${y?.name};`, 'ok = ~isnan(x) & ~isnan(y);', 'figure; hold on;');
      if (g && isCat(g) && g.kind !== 'multi') {
        L.push(...mCat(g, 'g'), 'for j = 1:numel(gCats)', '    in = ok & g == gCats(j);', '    scatter(x(in), y(in), 36, "filled", "DisplayName", gCats(j));', 'end');
      } else L.push('scatter(x(ok), y(ok), 36, "filled", "DisplayName", "Responses");');
      if (spec.fit !== false) L.push('p = polyfit(x(ok), y(ok), 1);', 'xs = linspace(min(x(ok)), max(x(ok)), 50);', 'plot(xs, polyval(p, xs), "LineWidth", 2, "DisplayName", "Trend line");');
      L.push('hold off; legend("Location", "best");', ...labels(), '', '[R, P] = corrcoef(x(ok), y(ok));', 'fprintf("r = %.3f, p = %.4f, n = %d\\n", R(1, 2), P(1, 2), sum(ok));');
      break;
    case 'line':
      L.push(`d = datetime(T.${x.name}, "InputFormat", "yyyy-MM-dd");`, 'd = d(~isnat(d));', '[days, ~, k] = unique(d);', 'counts = accumarray(k, 1);',
        ...(spec.cumulative ? ['counts = cumsum(counts);'] : []), 'figure;', 'plot(days, counts, "-o", "LineWidth", 2);', ...labels());
      break;
    case 'heatmap': {
      const col = (y ?? g)!;
      L.push(...mCat(x, 'x'), ...mCat(col, 'c'), 'counts = zeros(numel(xCats), numel(cCats));', 'for j = 1:numel(cCats)',
        `    counts(:, j) = ${mCounts(x, 'x', `${mIn(col, 'c', 'j')}`)};`, 'end', 'figure;', 'heatmap(cCats, xCats, counts);', `title(${mq(chart.title)});`,
        ...(chart.xlabel ? [`xlabel(${mq(chart.xlabel)});`] : []), ...(chart.ylabel ? [`ylabel(${mq(chart.ylabel)});`] : []));
      break;
    }
  }
  L.push('', '% Results shown in ResearchHub, for checking:', ...chart.stats.map((s) => `%   ${s}`));
  return L.filter((l, i, a) => !(l === '' && a[i - 1] === '')).join('\n') + '\n';
}

