const sq = (s: string) => `'${s.replace(/'/g, "''").replace(/\r?\n/g, ' ').slice(0, 250)}'`;

function spss(spec: ChartSpec, ds: Dataset, chart: ChartResult, cols: Column[]): string {
  const x = findVar(ds, spec.x)!, y = findVar(ds, spec.y), g = findVar(ds, spec.group);
  const fmt = (c: Column) => (c.kind === 'dummy' ? 'F1.0' : c.kind === 'number' ? 'F8.2' : c.v.kind === 'date' ? 'A10' : 'A255');
  const L = [
    `* ${chart.title}.`, `* Generated by ResearchHub (ScreenLab) from ${ds.n} responses. Change the FILE path below, then Run All.`, '',
    "GET DATA /TYPE=TXT /FILE='data.csv' /ENCODING='UTF8' /DELCASE=LINE /DELIMITERS=\",\" /QUALIFIER='\"'",
    '  /ARRANGEMENT=DELIMITED /FIRSTCASE=2 /VARIABLES=Response F8.0',
    ...cols.map((c, i) => `  ${c.name} ${fmt(c)}${i === cols.length - 1 ? '.' : ''}`),
    'VARIABLE LABELS', ...cols.map((c, i) => `  ${c.name} ${sq(c.label)}${i === cols.length - 1 ? '.' : ''}`), 'EXECUTE.', '',
  ];
  const multi = (v: StudioVar) => `MULT RESPONSE GROUPS=$${v.name} ${sq(v.label)} (${v.name}_1 TO ${v.name}_${v.categories.length} (1)) /FREQUENCIES=$${v.name}.`;
  switch (spec.type) {
    case 'bar': case 'barh': case 'pie':
      if (x.kind === 'multi') { L.push(multi(x)); break; }
      if (spec.type === 'pie') L.push(`GRAPH /PIE=COUNT BY ${x.name} /TITLE=${sq(chart.title)}.`);
      else if (g && g.name !== x.name && g.kind !== 'multi') L.push(`GRAPH /BAR(${spec.stacked ? 'STACK' : 'GROUPED'})=${spec.percent ? 'PCT' : 'COUNT'} BY ${x.name} BY ${g.name} /TITLE=${sq(chart.title)}.`, `CROSSTABS /TABLES=${x.name} BY ${g.name} /CELLS=COUNT COLUMN /STATISTICS=CHISQ.`);
      else L.push(`GRAPH /BAR(SIMPLE)=${spec.percent ? 'PCT' : 'COUNT'} BY ${x.name} /TITLE=${sq(chart.title)}.`, `FREQUENCIES VARIABLES=${x.name}.`);
      break;
    case 'histogram': L.push(`GRAPH /HISTOGRAM=${x.name} /TITLE=${sq(chart.title)}.`, `DESCRIPTIVES VARIABLES=${x.name} /STATISTICS=MEAN STDDEV MIN MAX.`); break;
    case 'box': case 'means': {
      const val = y ?? x, by = y ? (isCat(x) ? x : g) : g;
      if (!by || by.kind === 'multi') { L.push(`EXAMINE VARIABLES=${val.name} /PLOT=BOXPLOT /STATISTICS=DESCRIPTIVES.`); break; }
      L.push(spec.type === 'box' ? `EXAMINE VARIABLES=${val.name} BY ${by.name} /PLOT=BOXPLOT /STATISTICS=DESCRIPTIVES.` : `GRAPH /ERRORBAR(CI 95)=${val.name} BY ${by.name} /TITLE=${sq(chart.title)}.`,
        `AUTORECODE VARIABLES=${by.name} /INTO ${by.name}_n.`, `ONEWAY ${val.name} BY ${by.name}_n /STATISTICS DESCRIPTIVES WELCH.`);
      break;
    }
    case 'scatter': L.push(`GRAPH /SCATTERPLOT(BIVAR)=${x.name} WITH ${y?.name} /TITLE=${sq(chart.title)}.`, `CORRELATIONS /VARIABLES=${x.name} ${y?.name} /PRINT=TWOTAIL.`, `REGRESSION /DEPENDENT ${y?.name} /METHOD=ENTER ${x.name}.`); break;
    case 'line': L.push(`GRAPH /LINE(SIMPLE)=COUNT BY ${x.name} /TITLE=${sq(chart.title)}.`); break;
    case 'heatmap': { const col = (y ?? g)!; L.push(`CROSSTABS /TABLES=${x.name} BY ${col.name} /CELLS=COUNT ROW /STATISTICS=CHISQ /BARCHART.`); break; }
  }
  return L.join('\n') + '\n';
}

function stata(spec: ChartSpec, ds: Dataset, chart: ChartResult, cols: Column[]): string {
  const x = findVar(ds, spec.x)!, y = findVar(ds, spec.y), g = findVar(ds, spec.group);
  const tq = (s: string) => `"${s.replace(/"/g, "'").replace(/\r?\n/g, ' ').slice(0, 80)}"`;
  const strIdx = cols.map((c, i) => (c.kind === 'string' ? i + 2 : 0)).filter(Boolean);
  const L = [
    `* ${chart.title}`, `* Generated by ResearchHub (ScreenLab) from ${ds.n} responses. cd to the folder with data.csv, then run.`, '',
    `import delimited using "data.csv", varnames(1) case(preserve) encoding("utf-8")${strIdx.length ? ` stringcols(${strIdx.join(' ')})` : ''} clear`,
    ...cols.map((c) => `label variable ${c.name} ${tq(c.label)}`), '',
  ];
  // Choice questions become labelled numbers so graphs keep the questionnaire's order.
  const coded = new Set<string>();
  const code = (v: StudioVar) => {
    if (v.kind !== 'categorical' || coded.has(v.name)) return v.kind === 'categorical' ? `${v.name}_c` : v.name;
    coded.add(v.name);
    L.push(`label define ${v.name}_l ${v.categories.map((c, i) => `${i + 1} ${tq(c)}`).join(' ')}`, `generate ${v.name}_c = .`,
      ...v.categories.map((c, i) => `replace ${v.name}_c = ${i + 1} if ${v.name} == ${tq(c)}`), `label values ${v.name}_c ${v.name}_l`);
    return `${v.name}_c`;
  };
  const t = `title(${tq(chart.title)})`;
  const dummies = (v: StudioVar) => v.categories.map((_, j) => `${v.name}_${j + 1}`).join(' ');
  switch (spec.type) {
    case 'bar': case 'barh': case 'pie': {
      if (x.kind === 'multi') { L.push(`graph ${spec.type === 'barh' ? 'hbar' : 'bar'} (sum) ${dummies(x)}, ${t}`, `tabstat ${dummies(x)}, statistics(sum mean)`); break; }
      const xc = code(x);
      if (spec.type === 'pie') { L.push(`graph pie, over(${xc}) ${t}`); break; }
      const stat = spec.percent ? 'percent' : 'count';
      const cmd = spec.type === 'barh' ? 'hbar' : 'bar';
      if (g && g.name !== x.name && g.kind !== 'multi') { const gc = code(g); L.push(`graph ${cmd} (${stat}) Response, over(${gc}) over(${xc}) asyvars${spec.stacked ? ' stack' : ''} ${t}`, `tabulate ${xc} ${gc}, chi2 column`); }
      else L.push(`graph ${cmd} (${stat}) Response, over(${xc}${spec.sort ? ', sort(1) descending' : ''}) ${t}`, `tabulate ${xc}`);
      break;
    }
    case 'histogram': L.push(`histogram ${x.name}, frequency${x.scale ? ' discrete' : ` bin(${chart.model.kind === 'hist' ? chart.model.bins.length : 10})`} ${t}`, `summarize ${x.name}, detail`); break;
    case 'box': case 'means': {
      const val = y ?? x, by = y ? (isCat(x) ? x : g) : g;
      if (!by || by.kind === 'multi') { L.push(`graph box ${val.name}, ${t}`); break; }
      const bc = code(by);
      L.push(spec.type === 'box' ? `graph box ${val.name}, over(${bc}) ${t}` : `graph bar (mean) ${val.name}, over(${bc}) ${t}`, `mean ${val.name}, over(${bc})   // 95% CIs`,
        `oneway ${val.name} ${bc}, tabulate`, `* For two groups: ttest ${val.name}, by(${bc}) unequal`);
      break;
    }
    case 'scatter': L.push(`twoway (scatter ${y?.name} ${x.name})${spec.fit !== false ? ` (lfit ${y?.name} ${x.name})` : ''}, ${t}`, `pwcorr ${x.name} ${y?.name}, sig obs`, `regress ${y?.name} ${x.name}`); break;
    case 'line': L.push('preserve', `generate day = date(${x.name}, "YMD")`, 'format day %td', 'contract day', ...(spec.cumulative ? ['sort day', 'replace _freq = sum(_freq)'] : []), `twoway connected _freq day, ${t}`, 'restore'); break;
    case 'heatmap': { const col = (y ?? g)!; L.push(`tabulate ${code(x)} ${code(col)}, chi2 row`); break; }
  }
  return L.join('\n') + '\n';
}

export function script(lang: ScriptLang, spec: ChartSpec, ds: Dataset, chart: ChartResult, cols = columns(ds)): string {
  return lang === 'matlab' ? matlab(spec, ds, chart, cols) : lang === 'r' ? rScript(spec, ds, chart, cols) : lang === 'spss' ? spss(spec, ds, chart, cols) : stata(spec, ds, chart, cols);
}

export const SCRIPT_FILE: Record<ScriptLang, string> = { matlab: 'chart.m', r: 'chart.R', spss: 'chart.sps', stata: 'chart.do' };
export const SCRIPT_NAME: Record<ScriptLang, string> = { matlab: 'MATLAB', r: 'R', spss: 'SPSS', stata: 'Stata' };

/** The zip: data.csv, codebook.csv, the chart's numbers, all four scripts, and a README. */
export function exportPack(spec: ChartSpec, ds: Dataset, chart: ChartResult, opts: { includeEmail?: boolean; title: string }): Uint8Array {
  const cols = columns(ds, opts);
  const readme = [
    `${opts.title} — data export from ResearchHub (ScreenLab)`, `${ds.n} responses, exported ${new Date().toISOString().slice(0, 16).replace('T', ' ')} UTC.`, '',
    'data.csv       one row per response; columns are named Q1, Q2 … (see codebook.csv)',
    'codebook.csv   the full question text, type and answer options for every column',
    'chart_data.csv the numbers behind the chart that was on screen',
    'chart.m        MATLAB: open, then press Run (base MATLAB R2020a or newer)',
    'chart.R        R: setwd() to this folder, then source("chart.R")',
    'chart.sps      SPSS: open in a syntax window, check the FILE path, Run All',
    'chart.do       Stata: cd to this folder, then do chart.do', '',
    'Checkbox questions are split into one 0/1 column per option (Q3_1, Q3_2 …).',
    'Grid questions have one column per statement; ranking questions one column per option, holding its rank (1 = top).',
    ...(opts.includeEmail ? [] : ['Email-address questions are left out.']),
    '', 'Results shown in ResearchHub for this chart:', ...chart.stats.map((s) => `  ${s}`),
  ].join('\n');
  const files: Record<string, Uint8Array> = {
    'data.csv': strToU8(dataCsv(ds, cols)),
    'codebook.csv': strToU8(codebookCsv(ds, cols)),
    'chart_data.csv': strToU8('﻿' + Papa.unparse(chart.table.map((r) => r.map(String)))),
    'README.txt': strToU8(readme),
  };
  for (const l of ['matlab', 'r', 'spss', 'stata'] as ScriptLang[]) files[SCRIPT_FILE[l]] = strToU8(script(l, spec, ds, chart, cols));
  return zipSync(files, { level: 6 });
}

