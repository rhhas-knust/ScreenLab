// "Download for MATLAB / R / SPSS / Stata": a zip with tidy data, a codebook
// and a script that redraws the figure on screen. Variable names match the
// Chart Studio (Q1, Q4_2 …) so a command typed in ResearchHub and a line in the
// script mean the same thing.
import Papa from 'papaparse';
import { strToU8, zipSync } from 'fflate';
import { round } from './analytics';
import { tCrit95 } from './stats';
import { findVar, isCat, numsOf, type ChartResult, type ChartSpec, type Dataset, type StudioVar } from './studio';

export type ScriptLang = 'matlab' | 'r' | 'spss' | 'stata';

/** Columns written to data.csv. Checkbox questions become one 0/1 column per option. */
export interface Column { name: string; label: string; v: StudioVar; option?: string; kind: 'number' | 'string' | 'dummy' }

export function columns(ds: Dataset, opts: { includeEmail?: boolean } = {}): Column[] {
  const out: Column[] = [];
  for (const v of ds.vars) {
    if (v.email && !opts.includeEmail) continue;
    if (v.kind === 'multi') v.categories.forEach((o, j) => out.push({ name: `${v.name}_${j + 1}`, label: `${v.label} — ${o}`, v, option: o, kind: 'dummy' }));
    else out.push({ name: v.name, label: v.label, v, kind: v.kind === 'numeric' ? 'number' : 'string' });
  }
  return out;
}

/** Tidy CSV: one row per response, short column names, no BOM (MATLAB, R and Stata read it as-is). */
export function dataCsv(ds: Dataset, cols = columns(ds)): string {
  const rows = Array.from({ length: ds.n }, (_, i) => [String(i + 1), ...cols.map((c) => {
    const x = c.v.values[i];
    if (c.kind === 'dummy') return Array.isArray(x) ? (x.includes(c.option!) ? '1' : '0') : '';
    if (x == null) return '';
    return Array.isArray(x) ? x.join('; ') : String(x);
  })]);
  return Papa.unparse([['Response', ...cols.map((c) => c.name)], ...rows]);
}

export function codebookCsv(ds: Dataset, cols = columns(ds)): string {
  const type = (c: Column) => (c.kind === 'dummy' ? 'checkbox option (1 = ticked, 0 = not ticked, blank = question not answered)'
    : c.v.scale ? `scale ${c.v.categories[0]}–${c.v.categories.at(-1)}` : c.v.kind === 'numeric' ? 'number' : c.v.kind === 'categorical' ? 'single choice' : c.v.kind);
  return '﻿' + Papa.unparse([
    ['Variable', 'Question', 'Type', 'Answer options (in order)'],
    ['Response', 'Response number (order of submission)', 'number', ''],
    ...cols.map((c) => [c.name, c.label, type(c), c.kind === 'string' && c.v.kind === 'categorical' ? c.v.categories.join(' | ') : '']),
  ]);
}

